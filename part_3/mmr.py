
import numpy as np
import pandas as pd

GENRES = [
    "Action", "Adventure", "Animation", "Children's",
    "Comedy", "Crime", "Documentary", "Drama",
    "Fantasy", "Film-Noir", "Horror", "Musical",
    "Mystery", "Romance", "Sci-Fi", "Thriller",
    "War", "Western"
]

def genres_to_vector(genres: set[str]) -> np.ndarray:
    """
    Convert a genre set into an 18-dimensional binary vector.
    """
    genre_vector = np.array(
        [1.0 if genre in genres else 0.0 for genre in GENRES]
    )

    return genre_vector

def parse_genres(genres: str) -> set[str]:
    """
    Convert a MovieLens genre string into a set of genres.

    Example:
        "Action|Adventure|Comedy"
        -> {"Action", "Adventure", "Comedy"}
    """
    if not isinstance(genres, str) or not genres.strip():
        return set()

    return {
        genre.strip()
        for genre in genres.split("|")
        if genre.strip() and genre.strip() != "(no genres listed)"
    }


def cosine_distance(vector_a: np.ndarray, vector_b: np.ndarray) -> float:
    norm_a = np.linalg.norm(vector_a)
    norm_b = np.linalg.norm(vector_b)

    # Both movies have no genres
    if norm_a == 0 and norm_b == 0:
        return 0.0

    # Only one movie has no genres
    if norm_a == 0 or norm_b == 0:
        return 1.0

    cosine_similarity = np.dot(vector_a, vector_b) / (norm_a * norm_b)
    cosine_similarity = np.clip(cosine_similarity, 0.0, 1.0)

    return 1.0 - cosine_similarity


def normalize_relevance(scores: pd.Series) -> np.ndarray:
    """
    Normalize recommendation scores to the range [0, 1].

    If all scores are equal, use their original ranking instead.
    This preserves the original ordering when lambda = 1.
    """
    scores = pd.to_numeric(scores, errors="coerce").to_numpy(dtype=float)

    if not np.isfinite(scores).all():
        raise ValueError("All candidate scores must be finite.")

    min_score = scores.min()
    max_score = scores.max()

    if max_score > min_score:
        return (scores - min_score) / (max_score - min_score)

    # All scores are equal: use the original candidate order.
    n = len(scores)

    if n == 1:
        return np.ones(1)

    return 1.0 - np.arange(n) / (n - 1)


def rerank_mmr(
    candidates: pd.DataFrame,
    movies: pd.DataFrame,
    top_n: int = 10,
    lambda_: float = 0.5,
) -> pd.DataFrame:
    """
    Re-rank recommendation candidates using Maximal Marginal Relevance.

    Input:
    - candidates: DataFrame containing at least: user_id, movie_id, rank, score.

    This should be the larger candidate pool generated by the base recommender, 
    not just its final top_n recommendations.

    - movies: MovieLens movies DataFrame containing: movie_id, genres.

    - top_n: Number of recommendations to return per user.
    - lambda_: Relevance-diversity trade-off parameter in [0, 1].

        1.0 = relevance only.
        0.0 = diversity after selecting the first relevant item.

    Output:
    - DataFrame: Original candidate columns, with updated rank and 
    an additional mmr_score column.
    """
    
    required_candidate_columns = {"user_id", "movie_id", "rank", "score"}
    required_movie_columns = {"movie_id", "genres"}

    if not required_candidate_columns.issubset(candidates.columns):
        raise ValueError( "Candidates must contain user_id, movie_id, rank and score.")

    if not required_movie_columns.issubset(movies.columns):
        raise ValueError("Movies must contain movie_id and genres.")
    
    if movies["movie_id"].duplicated().any():
            raise ValueError("Duplicate movie IDs found in movies metadata.")
    
    if candidates.duplicated(["user_id", "movie_id"]).any():
        raise ValueError("Duplicate user/movie candidates found.")

    if not 0.0 <= lambda_ <= 1.0:
        raise ValueError("lambda_ must be between 0 and 1.")

    if top_n < 1:
        raise ValueError("top_n must be at least 1.")
    
    # Create a lookup from movie ID to its genre set.
    genre_lookup = {
        row.movie_id: genres_to_vector(parse_genres(row.genres))
        for row in movies[["movie_id", "genres"]].itertuples(index=False)
    }

    # Only consider candidates for which genre information is available.
    candidates = candidates[candidates["movie_id"].isin(genre_lookup)].copy()

    reranked_users = []

    for user_id, user_candidates in candidates.groupby("user_id", sort=False):
        # Preserve the original ranking as a deterministic tie-breaker.
        user_candidates = (user_candidates.sort_values("rank", kind="stable").reset_index(drop=True))

        # user_candidates = user_candidates.head(len(user_candidates)).copy()

        if user_candidates.empty:
            continue

        relevance = normalize_relevance(user_candidates["score"])

        movie_ids = user_candidates["movie_id"].tolist()

        selected_indices = []
        remaining_indices = list(range(len(movie_ids)))
        mmr_scores = {}

        # Greedily select movies until the requested list size is reached.
        while remaining_indices and len(selected_indices) < top_n:

            best_index = None
            best_mmr_score = -np.inf

            for candidate_index in remaining_indices:

                candidate_vector = genre_lookup[movie_ids[candidate_index]]

                # First recommendation is selected by relevance alone.
                if not selected_indices:
                    diversity = 0.0

                else:
                    # Distance to the most similar already selected item.
                    distances = []
                    for selected_index in selected_indices:

                        selected_vector = genre_lookup[movie_ids[selected_index]]

                        distances.append(
                            cosine_distance(
                                candidate_vector,
                                selected_vector
                            )
                        )

                    diversity = min(distances) # min cosine distance = max similarity

                # Mathematically:
                # similarity = 1 - cosine_distance, maximum similarity means minimum cosine distance
                # So MMR(i) = lambda . Rel(i) - (1 - lambda) . max(Similarity(i,j))
                #           = lambda . Rel(i) - (1 - lambda) . (1 - min(Distance(i,j)))
                #           = lambda . Rel(i) + (1 - lambda) . (min(Distance(i,j))  - (1 - lambda)
                # The final term - (1 - lambda) is constant across candidates. 
                # It does not affect which movie is selected so it can be omitted.
                # Final equation: MMR(i) = lambda . Rel(i) + (1 - lambda) . min(distance(i,j))
                mmr_score = (lambda_ * relevance[candidate_index] + (1.0 - lambda_) * diversity)

                # Strict comparison preserves original order on ties.
                if mmr_score > best_mmr_score:
                    best_mmr_score = mmr_score
                    best_index = candidate_index

            selected_indices.append(best_index)
            remaining_indices.remove(best_index)

            mmr_scores[best_index] = best_mmr_score

        # Build the final recommendation list.
        result = user_candidates.iloc[selected_indices].copy()

        result["rank"] = np.arange(1, len(result) + 1)

        result["mmr_score"] = [
            mmr_scores[index] for index in selected_indices
        ]

        reranked_users.append(result)

    if not reranked_users:
        return pd.DataFrame(columns=[*candidates.columns, "mmr_score"])

    return pd.concat(reranked_users, ignore_index=True)
